const SUPPORTED_LANGS = ["ja","en","ko","zh-CN","zh-TW","es"];

function detectLang(){
  const saved = localStorage.getItem('safelight-lang');
  if(saved && SUPPORTED_LANGS.includes(saved)) return saved;
  const nav = (navigator.language || 'ja');
  const exact = SUPPORTED_LANGS.find(l => l.toLowerCase() === nav.toLowerCase());
  if(exact) return exact;
  const base = nav.split('-')[0].toLowerCase();
  if(base === 'zh'){
    return /tw|hk|mo/i.test(nav) ? 'zh-TW' : 'zh-CN';
  }
  const baseMatch = SUPPORTED_LANGS.find(l => l.split('-')[0].toLowerCase() === base);
  return baseMatch || 'ja';
}

let currentLang = detectLang();

function t(key, vars){
  let str = (I18N[currentLang] && I18N[currentLang][key]) || (I18N.ja[key]) || key;
  if(vars){
    Object.keys(vars).forEach(k => { str = str.replace(new RegExp('\\{'+k+'\\}','g'), vars[k]); });
  }
  return str;
}

function applyI18n(lang){
  currentLang = SUPPORTED_LANGS.includes(lang) ? lang : 'ja';
  localStorage.setItem('safelight-lang', currentLang);
  document.documentElement.lang = currentLang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if(el.tagName === 'TITLE'){ document.title = val; }
    else { el.textContent = val; }
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    el.title = t(key);
  });
  const sel = document.getElementById('langSelect');
  if(sel) sel.value = currentLang;
}

document.addEventListener('DOMContentLoaded', () => {
  applyI18n(currentLang);
  const sel = document.getElementById('langSelect');
  if(sel){
    sel.addEventListener('change', () => applyI18n(sel.value));
  }
});

// ---- 表示テーマ(ライト/ダーク) ----
function detectTheme(){
  const saved = localStorage.getItem('safelight-theme');
  if(saved === 'light' || saved === 'dark') return saved;
  return 'dark'; // デフォルトはダーク
}
let currentTheme = detectTheme();
function applyTheme(theme){
  currentTheme = (theme === 'dark') ? 'dark' : 'light';
  localStorage.setItem('safelight-theme', currentTheme);
  document.documentElement.setAttribute('data-theme', currentTheme);
  const btn = document.getElementById('themeToggleBtn');
  if(btn){
    btn.textContent = currentTheme === 'dark' ? '☾' : '☀';
  }
}
applyTheme(currentTheme);
document.addEventListener('DOMContentLoaded', () => {
  const btn = document.getElementById('themeToggleBtn');
  if(btn) btn.addEventListener('click', () => applyTheme(currentTheme === 'dark' ? 'light' : 'dark'));
});
